#!/usr/bin/env python3
# build jc/magic_commands.py: the magic commands of the built-in parsers,
# mapped to the parser argument, so the CLI can find the parser for magic
# syntax without importing every parser module
from jc.lib import _builtin_magic_commands

magic_commands = _builtin_magic_commands()
width = max(len(repr(command)) for command in magic_commands) + 1

with open('jc/magic_commands.py', 'w') as f:
    print('"""jc - JSON Convert magic commands of the built-in parsers', file=f)
    print('', file=f)
    print('Generated by build-magic-commands.py from the `magic_commands` in each', file=f)
    print('parser. Do not edit by hand.', file=f)
    print('"""', file=f)
    print('from typing import Dict', file=f)
    print('', file=f)
    print('magic_commands: Dict[str, str] = {', file=f)
    for command in sorted(magic_commands):
        print(f'    {(repr(command) + ":").ljust(width)} {magic_commands[command]!r},', file=f)
    print('}', file=f)
